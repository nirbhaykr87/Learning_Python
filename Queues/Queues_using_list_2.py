# 2nd way of implementing the queues

# Insertion will be happen from front and deletion will be happen from back

queues = []

queues.insert(0,1) # Here we are inserting the element from front
queues.insert(0,2)
queues.insert(0,3)
queues.insert(0,4)

queues.pop()  # deleting the element from back

print(queues)
